import java.util.Scanner;
public class Main
{
	public static void main(String[] args) {
		Scanner sc =new Scanner(System.in);
		System.out.print("Enter a Input: ");
		int n=sc.nextInt();
	   
	    
	   for(int i=1;i<=n;i++){
	     
	         for(int j=0;j<3;j++){
	             System.out.print(i*3 -j + " ");
	             
	         }
	         System.out.println();
	         
	        
	       
	   }
	         
	              
	              
	           
	
	     
	 
	    
	    
	}
}
